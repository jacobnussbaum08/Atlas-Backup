from __future__ import annotations

import uuid

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect, text

from app.monitoring.health import HealthStatus, check_migrations, expected_migration_heads
from app.tests.integration.conftest import alembic_config

pytestmark = pytest.mark.integration


@pytest.fixture
def scratch_url(server_url):
    """A separate empty database, so up/down cycles don't disturb the shared one."""
    name = f"atlas_mig_{uuid.uuid4().hex[:12]}"
    admin = create_engine(server_url, isolation_level="AUTOCOMMIT")
    with admin.connect() as conn:
        conn.execute(text(f'CREATE DATABASE "{name}"'))
    try:
        yield server_url.set(database=name)
    finally:
        with admin.connect() as conn:
            conn.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
        admin.dispose()


def _tables(url) -> set[str]:
    engine = create_engine(url)
    try:
        return set(inspect(engine).get_table_names())
    finally:
        engine.dispose()


def test_upgrade_downgrade_upgrade_round_trip(scratch_url):
    config = alembic_config(scratch_url)

    command.upgrade(config, "head")
    assert _tables(scratch_url) >= {
        "assets",
        "asset_identifiers",
        "portfolio_accounts",
        "audit_logs",
    }

    command.downgrade(config, "base")
    assert _tables(scratch_url) == {"alembic_version"}

    command.upgrade(config, "head")
    assert "audit_logs" in _tables(scratch_url)


def test_models_and_migrations_do_not_drift(migrated_url):
    try:
        command.check(alembic_config(migrated_url))
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"ORM models differ from migrations: {exc}")


def test_readiness_migration_check_tracks_schema_version(scratch_url):
    engine = create_engine(scratch_url)
    heads = expected_migration_heads()
    try:
        assert check_migrations(engine, heads).status is HealthStatus.ERROR  # nothing applied

        command.upgrade(alembic_config(scratch_url), "head")
        result = check_migrations(engine, heads)
        assert result.status is HealthStatus.OK, result.detail

        command.downgrade(alembic_config(scratch_url), "base")
        assert check_migrations(engine, heads).status is HealthStatus.ERROR
    finally:
        engine.dispose()
