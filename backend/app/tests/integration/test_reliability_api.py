def issue(bench: Bench, name: str, *, trading: bool) -> str:
    with session_scope(bench.factory) as session:
        _record, token = operators.issue(
            session,
            name,
            can_control_trading=trading,
            actor=OPERATOR,
            reason="TEST FIXTURE credential",
            now=bench.now(),
        )
    return token


def client(bench: Bench, make_settings: Any, **overrides: Any) -> TestClient:
    app = create_app(
        make_settings(**overrides),
        clock=bench.clock,
        health_checks={},
        orchestration=bench.control,
        risk=bench.control.risk,
    )
    app.state.session_factory = bench.factory
    return TestClient(app)


def tick(runtime: Any) -> Any:
    return asyncio.run(runtime.orchestrator.tick())


def job_rows(bench: Bench, kind: JobKind) -> dict[str, OrchestrationJobRecord]:
    with session_scope(bench.factory) as session:
        rows = session.scalars(
            select(OrchestrationJobRecord).where(OrchestrationJobRecord.kind == kind)
        ).all()
        session.expunge_all()
        return {r.slot: r for r in rows}


# ====================================================================== named operators
def test_named_operators_are_recorded_as_themselves_and_need_trading_rights(bench, make_settings):
    trader = issue(bench, "alice", trading=True)
    viewer = issue(bench, "bob", trading=False)
    bench.enable()
    with client(bench, make_settings, operator_token="shared-fixture-token") as api:
        refused = api.post(
            f"{CONTROLS}/pause",
            json={"reason": "bob tries"},
            headers={"X-Atlas-Operator-Token": viewer},
        )
        assert refused.status_code == 403
        assert bench.mode() is TradingMode.ENABLED
        paused = api.post(
            f"{CONTROLS}/pause",
            json={"reason": "alice pauses"},
            headers={"Authorization": f"Bearer {trader}"},
        )
        assert paused.status_code == 200
        assert paused.json()["control"]["actor"] == "operator:alice"
        assert trader not in paused.text
        shared = api.post(
            f"{CONTROLS}/disable",
            json={"reason": "shared token (development)"},
            headers={"X-Atlas-Operator-Token": "shared-fixture-token"},
        )
        assert shared.status_code == 200
        assert shared.json()["control"]["actor"] == "operator:api"
        history = api.get("/api/v1/orchestration/controls/history").json()
        assert [h["actor"] for h in history[:2]] == ["operator:api", "operator:alice"]
    with session_scope(bench.factory) as session:
        alice = operators.active(session, "alice")
        assert alice is not None
        assert alice.last_used_at is not None
        assert alice.token_sha256 == operators.digest(trader)  # only the digest is stored
        rows = session.scalars(select(OperatorCredentialRecord)).all()
        assert all(trader not in str(vars(r)) for r in rows)


def test_a_revoked_or_unknown_credential_is_refused(bench, make_settings):
    token = issue(bench, "carol", trading=True)
    with session_scope(bench.factory) as session:
        operators.revoke(session, "carol", actor=OPERATOR, reason="left the desk", now=bench.now())
    with client(bench, make_settings) as api:
        for presented in (token, operators.new_token()):
            response = api.post(
                f"{CONTROLS}/emergency-stop",
                json={"reason": "should fail"},
                headers={"X-Atlas-Operator-Token": presented},
            )
            assert response.status_code == 401
            assert presented not in response.text
    assert bench.mode() is TradingMode.DISABLED
    with session_scope(bench.factory) as session, pytest.raises(operators.OperatorCredentialError):
        operators.issue(
            session,
            "carol",
            can_control_trading=False,
            actor=OPERATOR,
            reason="reuse",
            now=bench.now(),
        )


def test_the_paper_environment_accepts_only_named_trading_credentials_for_controls(
    bench, make_settings
):
    trader = issue(bench, "dana", trading=True)
    paper = {
        "environment": "paper",
        "postgres_password": PAPER_PASSWORD,
        "operator_token": "shared-paper-fixture-token",
    }
    with client(bench, make_settings, **paper) as api:
        shared = api.post(
            f"{CONTROLS}/emergency-stop",
            json={"reason": "shared token in paper"},
            headers={"X-Atlas-Operator-Token": "shared-paper-fixture-token"},
        )
        assert shared.status_code == 403
        kill = api.post(
            "/api/v1/risk/kill-switch/engage",
            json={"reason": "shared token in paper"},
            headers={"X-Atlas-Operator-Token": "shared-paper-fixture-token"},
        )
        assert kill.status_code == 403
        named = api.post(
            f"{CONTROLS}/emergency-stop",
            json={"reason": "named operator in paper"},
            headers={"X-Atlas-Operator-Token": trader},
        )
        assert named.status_code == 200
        assert named.json()["control"]["actor"] == "operator:dana"


# ====================================================================== alerts, metrics
def test_alerts_carry_their_action_and_acknowledgements_never_hide_them(bench, make_settings):
    bench.clock.advance(timedelta(minutes=5))
    tick(bench.orchestrator(require_protection_workers=True))  # no workers: gate closed
    viewer = issue(bench, "erin", trading=False)
    with client(bench, make_settings) as api:
        alerts = api.get("/api/v1/orchestration/alerts", params={"min_severity": "WARNING"}).json()
        by_type = {a["event_type"]: a for a in alerts}
        gate = by_type["ENTRY_GATE_CLOSED"]
        assert gate["severity"] == Severity.HIGH.value
        assert gate["action"]
        assert gate["acknowledged"] is False
        ack = api.post(
            f"/api/v1/orchestration/alerts/{gate['id']}/acknowledge",
            json={"note": "known: workers not started yet"},
            headers={"X-Atlas-Operator-Token": viewer},
        )
        assert ack.status_code == 200
        assert ack.json()["acknowledgements"][0]["actor"] == "operator:erin"
        open_alerts = api.get("/api/v1/orchestration/alerts", params={"open_only": True}).json()
        assert gate["id"] not in [a["id"] for a in open_alerts]
        everything = api.get("/api/v1/orchestration/alerts").json()
        assert gate["id"] in [a["id"] for a in everything]  # still in the history
        metrics = api.get("/api/v1/orchestration/metrics").json()
        assert metrics["simulated"] is True
        assert metrics["orchestrator"]["entry_gate_open"] is False
        assert metrics["position_monitor"]["alive"] is False
        assert set(metrics["jobs"]) >= {"RUNNING", "SUCCEEDED", "FAILED", "DEAD", "SUPERSEDED"}
        protection = api.get("/api/v1/orchestration/protection").json()
        assert protection["gate_open"] is False
        HeartbeatWriter(bench.factory, bench.clock, POSITION_MONITOR, interval_seconds=5).beat(
            passes=1
        )
        with session_scope(bench.factory) as session:
            bench.ex.broker.heartbeat(session, bench.now())
        assert api.get("/api/v1/orchestration/protection").json()["gate_open"] is True


# ====================================================================== CLI
def args(**kw: Any) -> argparse.Namespace:
    return argparse.Namespace(account=None, **kw)


def test_the_cli_issues_tokens_to_a_file_only_requeues_and_acknowledges(
    bench, tmp_path: Path, capsys
):
    s = settings(account_name=bench.account_name)
    target = tmp_path / "frank.token"
    assert (
        cli.run(
            bench.control,
            s,
            args(
                command="operator-add",
                name="frank",
                trading=True,
                token_file=str(target),
                actor=OPERATOR,
                reason="TEST FIXTURE operator",
            ),
        )
        == 0
    )
    token = target.read_text(encoding="utf-8").strip()
    assert token.startswith(operators.TOKEN_PREFIX)
    printed = capsys.readouterr().out
    assert token not in printed  # never printed
    assert target.name in printed
    with pytest.raises(operators.OperatorCredentialError):  # never overwrites a file
        cli.run(
            bench.control,
            s,
            args(
                command="operator-add",
                name="frank2",
                trading=False,
                token_file=str(target),
                actor=OPERATOR,
                reason="again",
            ),
        )
    cli.run(bench.control, s, args(command="operators"))
    listing = capsys.readouterr().out
    assert "operator:frank" in listing
    assert operators.digest(token) not in listing

    # A dead letter, requeued from the CLI.
    def boom() -> dict[str, Any]:
        raise RuntimeError("TEST FIXTURE failure")

    runner = JobRunner(
        bench.factory, bench.clock, owner="t", lease=timedelta(minutes=5), max_attempts=1
    )
    [dead] = runner.run_due([JobSpec(JobKind.RISK_MONITOR, every(300), boom, interval_seconds=300)])
    job_id = job_rows(bench, JobKind.RISK_MONITOR)[dead.slot].id
    assert (
        cli.run(
            bench.control,
            s,
            args(command="requeue-job", id=job_id, actor=OPERATOR, reason="cause fixed"),
        )
        == 0
    )
    assert '"status": "FAILED"' in capsys.readouterr().out
    [event] = [e for e in bench.health_events("ORCHESTRATION_JOB_DEAD")]
    assert (
        cli.run(
            bench.control,
            s,
            args(command="ack-alert", id=event.id, actor=OPERATOR, note="requeued after the fix"),
        )
        == 0
    )
    assert '"acknowledged": true' in capsys.readouterr().out


def test_paper_environment_cli_actions_need_an_active_named_operator(bench, tmp_path: Path):
    s = settings(account_name=bench.account_name)
    paper = Environment.PAPER
    # The very first credential bootstraps; afterwards the actor must be an active operator.
    first = args(
        command="operator-add",
        name="grace",
        trading=True,
        token_file=str(tmp_path / "grace.token"),
        actor="operator:grace",
        reason="bootstrap the first operator",
    )
    assert cli.run(bench.control, s, first, environment=paper) == 0
    stranger = args(command="enable", actor="operator:mallory", reason="not registered")
    with pytest.raises(operators.OperatorCredentialError):
        cli.run(bench.control, s, stranger, environment=paper)
    assert bench.mode() is TradingMode.DISABLED
    known = args(command="enable", actor="operator:grace", reason="registered operator")
    assert cli.run(bench.control, s, known, environment=paper) == 0
    assert bench.mode() is TradingMode.ENABLED
